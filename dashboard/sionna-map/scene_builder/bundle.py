#!/usr/bin/env python3
import argparse
import json
import pprint
import shutil
import sys
import zipfile
from pathlib import Path

import run_scene as rs


SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""load_scene.py - reproduce this scene outside the platform that exported it.

Generated by SionnaRTStudio-adjacent tooling from the scene manifest; see manifest.json for
the fingerprint and the software versions this was produced against.

    pip install sionna-rt
    python load_scene.py

Writes cir.npz next to this script: the path coefficients, the delays, and - when a
subcarrier grid is configured below - the frequency response.

Coordinates are ENU metres (x=East, y=North, z=Up) with the ground plane at z=0, which is
the same frame the platform uses, so positions here match the ones on the map.
"""
import numpy as np
from sionna.rt import (PathSolver, PlanarArray, Receiver, Transmitter, load_scene,
                       subcarrier_frequencies)

HERE = __import__("pathlib").Path(__file__).resolve().parent

# --- what the XML cannot carry --------------------------------------------- #
CARRIER_HZ = {carrier_hz!r}
TX_ARRAY = {tx_array!r}
RX_ARRAY = {rx_array!r}
TRANSMITTERS = {transmitters}
RECEIVERS = {receivers}
SOLVER = {solver}

# Set to 0 to skip the frequency response and write coefficients and delays only.
NUM_SUBCARRIERS = {num_subcarriers!r}
SUBCARRIER_SPACING_HZ = {subcarrier_spacing_hz!r}
NORMALIZE_DELAYS = {normalize_delays!r}

scene = load_scene(str(HERE / "scene.xml"))
scene.frequency = CARRIER_HZ

scene.tx_array = PlanarArray(num_rows=TX_ARRAY["rows"], num_cols=TX_ARRAY["cols"],
                             pattern=TX_ARRAY["pattern"], polarization=TX_ARRAY["pol"])
scene.rx_array = PlanarArray(num_rows=RX_ARRAY["rows"], num_cols=RX_ARRAY["cols"],
                             pattern=RX_ARRAY["pattern"], polarization=RX_ARRAY["pol"])

for t in TRANSMITTERS:
    scene.add(Transmitter(name=t["name"], position=t["position"],
                          orientation=t["orientation"], power_dbm=t["power_dbm"]))
for r in RECEIVERS:
    scene.add(Receiver(name=r["name"], position=r["position"]))

print("scene      :", scene)
print("carrier    : %.5f GHz" % (CARRIER_HZ / 1e9))
print("devices    : %d transmitters, %d receivers" % (len(TRANSMITTERS), len(RECEIVERS)))

paths = PathSolver()(scene, **SOLVER)

a, tau = paths.cir(out_type="numpy", normalize_delays=NORMALIZE_DELAYS)
a, tau = np.asarray(a), np.asarray(tau)
out = {{"a": a, "tau": tau}}

if NUM_SUBCARRIERS > 0:
    freqs = subcarrier_frequencies(NUM_SUBCARRIERS, SUBCARRIER_SPACING_HZ)
    out["h_freq"] = np.asarray(paths.cfr(frequencies=freqs,
                                         normalize_delays=NORMALIZE_DELAYS,
                                         out_type="numpy"))
    out["frequencies"] = np.asarray(freqs)

out["tx_names"] = np.array([t["name"] for t in TRANSMITTERS])
out["rx_names"] = np.array([r["name"] for r in RECEIVERS])
out["carrier_hz"] = CARRIER_HZ

np.savez_compressed(HERE / "cir.npz", **out)

# The total gain per link, which is the number to compare against the platform: it is what
# the exported manifest records under link_gain_db.
power = np.sum(np.abs(a) ** 2, axis=tuple(i for i in range(a.ndim) if i not in (0, 2)))
with np.errstate(divide="ignore"):
    gain_db = 10.0 * np.log10(power + 1e-30)
print()
print("link gain (dB), receivers down, transmitters across:")
for ri, rx in enumerate(RECEIVERS):
    row = "  %-12s" % rx["name"]
    for ti in range(len(TRANSMITTERS)):
        row += " %10.2f" % gain_db[ri, ti]
    print(row)
print()
print("wrote", HERE / "cir.npz", "shapes a=%s tau=%s" % (a.shape, tau.shape))
'''


GAIN_CHECK_MEASURED = """That writes `cir.npz` beside the script and prints the link gains, which should match the
`link_gain_db` recorded in `manifest.json` to within the solver's own run-to-run variation
(about one part in 10,000 — the ray tracer is not bit-reproducible even with the seed fixed)."""

"""What the standalone run should agree with, when the platform measured it."""

GAIN_CHECK_UNTRACED = """That writes `cir.npz` beside the script and prints the link gains. There is no
`link_gain_db` in `manifest.json` to compare them against: this scene was bundled without
having been solved on the platform, so nothing has measured one. The numbers the script
prints are the first for this scene."""

"""The same paragraph for a scene that was never traced.

Saying there is nothing to compare against beats sending the reader to look for a field that
is absent, which reads as a broken export rather than an untraced scene."""

README_TEMPLATE = """# {city} — Sionna RT scene

A self-contained ray-tracing scene exported from the platform. Everything needed to
reproduce the solve is here; nothing outside this directory is referenced.

```bash
pip install sionna-rt
python load_scene.py
```

{gain_check}

## What is here

| File | Contents |
| --- | --- |
| `scene.xml` | Mitsuba scene, ITU radio materials, relative mesh paths |
| `meshes/` | Ground plane plus one extruded prism per building ({nof_meshes} files) |
| `load_scene.py` | The Python-side setup the XML cannot hold, replayed |
| `manifest.json` | Fingerprint, device placements, solver settings, software versions |
| `README.md` | This file |

## The scene

- **Area**: {city}, {nof_tx} transmitter(s) and {nof_rx} receiver(s)
- **Carrier**: {carrier_ghz:.5f} GHz
- **Transmit array**: {tx_rows}x{tx_cols} {tx_pattern}, polarization {tx_pol}
- **Geometry fingerprint**: `{geometry_short}`
- **Building source**: {source_provider} {source_release}

Coordinates are ENU metres (x=East, y=North, z=Up), ground plane at z=0. Device heights are
roof-aware: a device standing over a building footprint sits on it.

## Reading the output

```python
import numpy as np
d = np.load("cir.npz")
a, tau = d["a"], d["tau"]
print(a.shape)   # [num_rx, num_rx_ant, num_tx, num_tx_ant, path, time]
```

Delays come back as `[num_rx, num_tx, path]`: with a synthetic array the geometry is the
same across antenna ports, so Sionna stores one copy rather than a broadcast one.
"""


def py_literal(obj, indent=4):
    return pprint.pformat(obj, indent=indent, width=88, sort_dicts=False)


def build_script(cfg, num_subcarriers, subcarrier_spacing_hz, normalize_delays, max_depth, sp):
    solver = {
        "max_depth": int(max_depth),
        "los": bool(sp.get("los", True)),
        "specular_reflection": bool(sp.get("specular", True)),
        "diffuse_reflection": bool(sp.get("diffuse", False)),
        "refraction": bool(sp.get("refraction", True)),
        "diffraction": bool(sp.get("diffraction", False)),
        "edge_diffraction": bool(sp.get("edge_diffraction", False)),
        "synthetic_array": bool(sp.get("synthetic_array", True)),
        "samples_per_src": int(sp.get("samples_per_src", 1000000)),
        "max_num_paths_per_src": int(sp.get("max_paths_per_src", 1000000)),
        "seed": int(sp.get("seed", 42)),
    }
    return SCRIPT_TEMPLATE.format(
        carrier_hz=float(cfg["freq"]),
        tx_array={"rows": cfg["rows"], "cols": cfg["cols"],
                  "pattern": cfg["tx_pattern"], "pol": cfg["tx_pol"]},
        rx_array={"rows": 1, "cols": 1,
                  "pattern": cfg["rx_pattern"], "pol": cfg["rx_pol"]},
        transmitters=py_literal(cfg["tx_placements"]),
        receivers=py_literal(cfg["rx_placements"]),
        solver=py_literal(solver),
        num_subcarriers=int(num_subcarriers),
        subcarrier_spacing_hz=float(subcarrier_spacing_hz),
        normalize_delays=bool(normalize_delays),
    ), solver


def export_bundle(manifest, scene_dir, out_zip, srate_hz, max_depth, sp=None,
                  num_subcarriers=0, subcarrier_spacing_hz=30e3, normalize_delays=True,
                  tx_select=None, provenance=None, link_gain_db=None, link_paths=None,
                  log=print):
    sp = sp or {}
    scene_dir = Path(scene_dir)
    xml = scene_dir / "scene.xml"
    meshes = scene_dir / "meshes"
    if not xml.exists():
        raise SystemExit(f"no scene.xml at {xml} - build the scene first")

    cfg = rs.scene_config(manifest, srate_hz, tx_select=tx_select, sp=sp)
    script, solver = build_script(cfg, num_subcarriers, subcarrier_spacing_hz,
                                  normalize_delays, max_depth, sp)

    mesh_files = sorted(meshes.glob("*.ply")) if meshes.is_dir() else []
    city = (manifest.get("city") or "scene")

    record = {
        "format": "sionna-scene-bundle",
        "version": 1,
        "city": city,
        "carrier_hz": float(cfg["freq"]),
        "srate_hz": float(srate_hz),
        "tx_array": {"rows": cfg["rows"], "cols": cfg["cols"],
                     "pattern": cfg["tx_pattern"], "pol": cfg["tx_pol"]},
        "rx_array": {"rows": 1, "cols": 1,
                     "pattern": cfg["rx_pattern"], "pol": cfg["rx_pol"]},
        "transmitters": cfg["tx_placements"],
        "receivers": cfg["rx_placements"],
        "solver": solver,
        "num_subcarriers": int(num_subcarriers),
        "subcarrier_spacing_hz": float(subcarrier_spacing_hz),
        "normalize_delays": bool(normalize_delays),
        "nof_meshes": len(mesh_files),
        "coordinates": "ENU metres, x=East y=North z=Up, ground plane at z=0",
    }
    if provenance:
        record["provenance"] = provenance
    if link_gain_db is not None:
        record["link_gain_db"] = link_gain_db
    if link_paths is not None:
        record["link_paths"] = link_paths

    src = cfg["source"] if "source" in cfg else {}
    buildings = (manifest.get("buildings") or {})
    readme = README_TEMPLATE.format(
        city=city,
        gain_check=(GAIN_CHECK_MEASURED if link_gain_db else GAIN_CHECK_UNTRACED),
        nof_meshes=len(mesh_files),
        nof_tx=len(cfg["tx_placements"]),
        nof_rx=len(cfg["rx_placements"]),
        carrier_ghz=float(cfg["freq"]) / 1e9,
        tx_rows=cfg["rows"], tx_cols=cfg["cols"],
        tx_pattern=cfg["tx_pattern"], tx_pol=cfg["tx_pol"],
        geometry_short=((provenance or {}).get("scene") or {}).get("geometry_short", "unknown"),
        source_provider=buildings.get("source", "unknown"),
        source_release=buildings.get("release", ""),
    )

    out_zip = Path(out_zip)
    out_zip.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(xml, "scene.xml")
        for m in mesh_files:
            z.write(m, f"meshes/{m.name}")
        z.writestr("load_scene.py", script)
        z.writestr("manifest.json", json.dumps(record, indent=2))
        z.writestr("README.md", readme)

    size = out_zip.stat().st_size
    log(f"Bundle        : {out_zip}  ({size/1024/1024:.2f} MB)")
    log(f"  scene.xml   : 1")
    log(f"  meshes      : {len(mesh_files)}")
    log(f"  load_scene.py, manifest.json, README.md")

    return {
        "ok": True,
        "out": str(out_zip),
        "bytes": size,
        "nof_meshes": len(mesh_files),
        "city": city,
        "carrier_hz": float(cfg["freq"]),
        "nof_tx": len(cfg["tx_placements"]),
        "nof_rx": len(cfg["rx_placements"]),
        "members": ["scene.xml", "meshes/", "load_scene.py", "manifest.json", "README.md"],
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("manifest")
    ap.add_argument("--scene-dir", required=True, help="directory holding scene.xml and meshes/")
    ap.add_argument("--out", required=True, help="path to write the .zip to")
    ap.add_argument("--srate", type=float, default=61.44e6)
    ap.add_argument("--max-depth", type=int, default=5)
    ap.add_argument("--tx", default=None)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--subcarriers", type=int, default=0)
    ap.add_argument("--subcarrier-spacing", type=float, default=30e3)
    ap.add_argument("--provenance", default="", help="path to a provenance record to embed")
    ap.add_argument("--link-gain-db", default="",
                    help="JSON list of what the platform measured, for checking a reproduction")
    ap.add_argument("--link-paths", default="",
                    help="JSON map of receiver name to the path count behind its gain")
    rs._bool_pair(ap, "normalize-delays", True, "shift the first arrival to tau=0")
    rs._bool_pair(ap, "los", True, "include the direct path")
    rs._bool_pair(ap, "specular", True, "mirror-like reflections")
    rs._bool_pair(ap, "diffuse", False, "scattering off rough surfaces")
    rs._bool_pair(ap, "refraction", True, "transmission through materials")
    rs._bool_pair(ap, "diffraction", False, "bending around edges")
    rs._bool_pair(ap, "edge-diffraction", False, "wedge diffraction")
    rs._bool_pair(ap, "synthetic-array", True, "one solve for the whole array")
    ap.add_argument("--array-pattern", default=None)
    ap.add_argument("--array-pol", default=None)
    ap.add_argument("--array-rows", type=int, default=None)
    ap.add_argument("--array-cols", type=int, default=None)
    ap.add_argument("--rx-pattern", default="iso")
    ap.add_argument("--rx-pol", default="V")
    ap.add_argument("--freq-hz", type=float, default=None)
    ap.add_argument("--num-taps", type=int, default=None)
    ap.add_argument("--samples-per-src", type=int, default=1000000)
    ap.add_argument("--max-paths-per-src", type=int, default=1000000)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    m = rs.load_manifest(args.manifest)
    log = (lambda *a: print(*a, file=sys.stderr, flush=True)) if args.json else print
    sp = {k: getattr(args, k) for k in (
        "los", "specular", "diffuse", "refraction", "diffraction", "edge_diffraction",
        "synthetic_array", "array_pattern", "array_pol", "array_rows", "array_cols",
        "rx_pattern", "rx_pol", "freq_hz", "num_taps", "samples_per_src",
        "max_paths_per_src", "seed")}

    prov = None
    if args.provenance:
        try:
            prov = json.loads(Path(args.provenance).read_text())
        except (OSError, ValueError):
            prov = None
    gains = None
    if args.link_gain_db:
        try:
            gains = json.loads(args.link_gain_db)
        except ValueError:
            gains = None
    npaths = None
    if args.link_paths:
        try:
            npaths = json.loads(args.link_paths)
        except ValueError:
            npaths = None

    result = export_bundle(m, args.scene_dir, args.out, args.srate, args.max_depth, sp=sp,
                           num_subcarriers=args.subcarriers,
                           subcarrier_spacing_hz=args.subcarrier_spacing,
                           normalize_delays=args.normalize_delays,
                           tx_select=args.tx, provenance=prov, link_gain_db=gains,
                           link_paths=npaths, log=log)
    if args.json:
        print(json.dumps(result))


if __name__ == "__main__":
    main()
